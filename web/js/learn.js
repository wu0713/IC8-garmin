async function viewLearn(focus) {
  let zones = null;
  try {
    const r = await api("/api/runner");
    const mx = r.numbers.find((n) => n.key === "max_hr")?.value;
    if (mx) zones = mx;
  } catch { /* 還沒連結也可以看 */ }
  const zoneTable = (mx) => `<div class="lr-zones">
    ${[["1–2 區", 0, 0.74, "輕鬆、長跑"], ["3 區", 0.75, 0.84, "馬拉松配速"], ["4 區", 0.85, 0.90, "節奏、閾值"], ["5 區", 0.91, 1, "間歇、衝刺"]]
      .map(([n, a, b, w]) => `<div><b>${n}</b><span class="num">${a ? Math.round(mx * a) : "–"}–${Math.round(mx * b)}</span><small>${w}</small></div>`).join("")}
    </div><p class="muted">依你的最大心率 ${mx} 計算。</p>`;

  $app.innerHTML = `
    ${appbar("跑步小教室", { back: true })}
    <label class="lr-search">${ico("search")}<input type="search" id="lq" placeholder="搜尋，例如：間歇、HRV、配速" aria-label="搜尋名詞"></label>
    <nav class="lr-toc">${LEARN.map((s) => `<a href="#/learn/${s.id}">${ico(s.icon)}${esc(s.title)}</a>`).join("")}</nav>
    ${LEARN.map((s) => `<section class="lr-sec" id="lr-${s.id}">
      <h2>${ico(s.icon)}${esc(s.title)}</h2>
      ${s.items.map((it) => `<details class="card lr-item" id="lr-${it.id}" data-q="${esc((it.t + it.d.join("")).toLowerCase())}">
        <summary><b>${esc(it.t)}</b>${it.tag ? `<span class="pt ${{ 輕鬆: "easy", 中強度: "moderate", 強度: "hard", 休息: "" }[it.tag]}">${it.tag}</span>` : ""}</summary>
        ${it.d.map((p) => `<p>${esc(p)}</p>`).join("")}
        ${it.personal === "zones" && zones ? zoneTable(zones) : ""}
      </details>`).join("")}
    </section>`).join("")}
    <p class="muted" style="margin:16px 4px">這裡的說明是一般性的訓練知識，不能取代醫師或專業教練的建議。</p>`;
  bindCommon();

  const q = document.getElementById("lq");
  q.oninput = () => {
    const v = q.value.trim().toLowerCase();
    document.querySelectorAll(".lr-item").forEach((el) => {
      const hit = !v || el.dataset.q.includes(v);
      el.hidden = !hit;
      if (v && hit) el.open = true;
    });
    document.querySelectorAll(".lr-sec").forEach((s) => (s.hidden = ![...s.querySelectorAll(".lr-item")].some((x) => !x.hidden)));
  };
  if (focus) {
    const el = document.getElementById(`lr-${focus}`);
    if (el) {
      if (el.tagName === "DETAILS") el.open = true;
      setTimeout(() => el.scrollIntoView({ block: "start" }), 50);
    }
  }
}

